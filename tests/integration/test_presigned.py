class TestPresignedGet:
    """Tests for presigned GET URLs."""

    def test_presigned_get_basic(self, s3_client, endpoint_url):
        """Generate presigned GET URL and fetch with plain HTTP."""
        data = b"presigned get test"
        s3_client.put_object(Bucket=BUCKET, Key="presigned.txt", Body=data)

        url = s3_client.generate_presigned_url(
            "get_object",
            Params={"Bucket": BUCKET, "Key": "presigned.txt"},
            ExpiresIn=3600,
        )

        resp = requests.get(url, timeout=10)
        assert resp.status_code == 200
        assert resp.content == data

    def test_presigned_get_binary(self, s3_client, endpoint_url):
        """Presigned GET works with binary data."""
        data = bytes(range(256)) * 100
        s3_client.put_object(Bucket=BUCKET, Key="binary.bin", Body=data)

        url = s3_client.generate_presigned_url(
            "get_object",
            Params={"Bucket": BUCKET, "Key": "binary.bin"},
            ExpiresIn=3600,
        )

        resp = requests.get(url, timeout=10)
        assert resp.status_code == 200
        assert resp.content == data

    def test_presigned_get_with_special_chars(self, s3_client, endpoint_url):
        """Presigned GET works with special characters in key."""
        data = b"special chars test"
        key = "path/to/file with spaces.txt"
        s3_client.put_object(Bucket=BUCKET, Key=key, Body=data)

        url = s3_client.generate_presigned_url(
            "get_object",
            Params={"Bucket": BUCKET, "Key": key},
            ExpiresIn=3600,
        )

        resp = requests.get(url, timeout=10)
        assert resp.status_code == 200
        assert resp.content == data

    def test_presigned_get_nonexistent_key(self, s3_client, endpoint_url):
        """Presigned GET for non-existent key returns 404."""
        url = s3_client.generate_presigned_url(
            "get_object",
            Params={"Bucket": BUCKET, "Key": "does-not-exist.txt"},
            ExpiresIn=3600,
        )

        resp = requests.get(url, timeout=10)
        assert resp.status_code == 404

    def test_presigned_get_response_overrides(self, s3_client, endpoint_url):
        """Presigned GET with response-content-type override."""
        data = b"response override test"
        s3_client.put_object(
            Bucket=BUCKET,
            Key="override.txt",
            Body=data,
            ContentType="text/plain",
        )

        url = s3_client.generate_presigned_url(
            "get_object",
            Params={
                "Bucket": BUCKET,
                "Key": "override.txt",
                "ResponseContentType": "application/octet-stream",
                "ResponseContentDisposition": "attachment; filename=download.txt",
            },
            ExpiresIn=3600,
        )

        resp = requests.get(url, timeout=10)
        assert resp.status_code == 200
        assert resp.content == data
        assert resp.headers.get("Content-Type") == "application/octet-stream"
        assert "attachment" in resp.headers.get("Content-Disposition", "")


