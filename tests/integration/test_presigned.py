class TestAdminPresign:
    """Tests for the admin presign endpoint."""

    def test_admin_presign_get(self, s3_client, endpoint_url, creds):
        """Admin presign endpoint generates a valid GET URL."""
        data = b"admin presign test"
        s3_client.put_object(Bucket=BUCKET, Key="admin-presign.txt", Body=data)

        url = f"{endpoint_url}/admin/presign"
        resp = signed_request(
            "POST",
            url,
            creds,
            data={"bucket": BUCKET, "key": "admin-presign.txt"},
        )
        assert resp.status_code == 200
        body = resp.json()
        assert "url" in body
        assert "expires_at" in body

        # Fetch the presigned URL
        get_resp = requests.get(body["url"], timeout=10)
