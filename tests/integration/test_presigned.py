class TestPresignedSecurity:
    """Tests for presigned URL security and expiration."""

    def test_tampered_signature_rejected(self, s3_client, endpoint_url):
        """Tampering with the signature should be rejected."""
        data = b"tamper test"
        s3_client.put_object(Bucket=BUCKET, Key="tamper.txt", Body=data)

        url = s3_client.generate_presigned_url(
            "get_object",
            Params={"Bucket": BUCKET, "Key": "tamper.txt"},
            ExpiresIn=3600,
        )

        # Tamper with the signature
        tampered_url = url.replace("X-Amz-Signature=", "X-Amz-Signature=0000")
        resp = requests.get(tampered_url, timeout=10)
        assert resp.status_code == 403

    def test_tampered_path_rejected(self, s3_client, endpoint_url):
        """Changing the object key should be rejected."""
        s3_client.put_object(Bucket=BUCKET, Key="original.txt", Body=b"original")
        s3_client.put_object(Bucket=BUCKET, Key="other.txt", Body=b"other")

        url = s3_client.generate_presigned_url(
            "get_object",
            Params={"Bucket": BUCKET, "Key": "original.txt"},
            ExpiresIn=3600,
        )

        # Replace key in URL path
        tampered_url = url.replace("/original.txt", "/other.txt")
        resp = requests.get(tampered_url, timeout=10)
        assert resp.status_code == 403

    def test_max_expires_accepted(self, s3_client, endpoint_url):
        """Maximum expiry of 604800 seconds (7 days) is accepted."""
        data = b"max expires test"
        s3_client.put_object(Bucket=BUCKET, Key="maxexp.txt", Body=data)

        url = s3_client.generate_presigned_url(
            "get_object",
            Params={"Bucket": BUCKET, "Key": "maxexp.txt"},
            ExpiresIn=604800,
        )

        resp = requests.get(url, timeout=10)
        assert resp.status_code == 200
        assert resp.content == data


